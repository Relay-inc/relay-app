#!/usr/bin/env python3
"""Generate the project index from the project cards (frontmatter of each project note).

Reads every card under Contexts/<context>/Projects/ and writes
  - System/rules/core/work-state.md  (one row per project: | [[Name]] | status | last | index |)
  - System/index/repos.json          ({repo path prefix: project note}, ~ expanded)
A context is a folder under Contexts/. Cards with `status: Closed` are skipped. No dependencies.

Usage: build-index.py [--check] [--selftest]
  --check     print what would change (unified diff), write nothing, exit 1 when out of date
"""
import datetime as dt
import difflib
import glob
import json
import os
import re
import sys

VAULT = os.environ.get("VAULT") or os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SKIP_DIRS = {"Documents", "Communication", "_archive"}
MAX_INDEX = 160

HEADER = """# Work State

*Index of all projects, one line each. The full state lives in the project note under `## Status`. Read that section as soon as a project comes up, this file is only the map.*

*Generated by `System/scripts/build-index.py` from the project cards (`status`, `last`, `index`). Edit the card, not this file.*

---

## Last Session
- **Date:** {today}

## States
Active = being worked on. Blocked = waiting on someone. Quiet = 30+ days without activity, still relevant. Paused = deliberately on hold.

## Projects
"""
TABLE_HEAD = "| Project | State | Last | Summary |\n|---|---|---|---|\n"


def frontmatter(text):
    """Tiny YAML reader: top-level scalars, block lists, flow lists. Enough for the card fields."""
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not m:
        return {}
    fm, key = {}, None
    for line in m.group(1).split("\n"):
        item = re.match(r"^\s+-\s*(.*)$", line)
        if item and key is not None and isinstance(fm.get(key), list):
            fm[key].append(unquote(item.group(1)))
            continue
        kv = re.match(r"^([A-Za-z][\w-]*):\s*(.*)$", line)
        if kv:
            key, val = kv.group(1), kv.group(2).strip()
            if val == "":
                fm[key] = []
            elif val.startswith("[") and val.endswith("]"):
                fm[key] = [unquote(v) for v in re.findall(r'"[^"]*"|[^,\s][^,]*', val[1:-1])]
            else:
                fm[key] = unquote(val)
        elif line.startswith("  ") and key is not None and isinstance(fm.get(key), list) and not fm[key]:
            fm[key] = ""  # nested map (systemen): not needed here
    return fm


def unquote(v):
    v = v.strip()
    if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
        v = v[1:-1]
    return v


def contexts(vault):
    root = os.path.join(vault, "Contexts")
    return sorted(d for d in os.listdir(root) if os.path.isdir(os.path.join(root, d)) and d[0] not in "._") \
        if os.path.isdir(root) else []


def scalar(fm, key, rel, warnings):
    """A card field as one string. A YAML list keeps its first item, with a warning, instead of crashing."""
    v = fm.get(key)
    if isinstance(v, list):
        if v:
            warnings.append(f"{rel}: {key} is a list, using the first item")
        return v[0] if v else ""
    return v or ""


def card_paths(vault):
    paths = []
    for p in glob.glob(os.path.join(vault, "Contexts", "*", "Projects", "**", "*.md"), recursive=True):
        rel = os.path.relpath(p, vault).split(os.sep)
        inner = rel[3:]  # below Projects/
        if any(part in SKIP_DIRS for part in inner[:-1]):
            continue
        stem = os.path.splitext(inner[-1])[0]
        # flat note Projects/<P>.md or folder note Projects/<P>/<P>.md
        if len(inner) == 1 or (len(inner) == 2 and inner[0] == stem):
            paths.append(p)
    return sorted(set(paths))


def load_cards(vault):
    cards, warnings, known = [], [], contexts(vault)
    for p in card_paths(vault):
        rel = os.path.relpath(p, vault)
        fm = frontmatter(open(p, encoding="utf-8").read())
        name = os.path.splitext(os.path.basename(p))[0]
        status, last = scalar(fm, "status", rel, warnings), scalar(fm, "last", rel, warnings)
        if not status:
            warnings.append(f"{rel}: no status, skipped")
            continue
        if status == "Closed":
            continue
        ctx = re.sub(r"[\[\]\"]", "", scalar(fm, "context", rel, warnings))
        if ctx not in known:
            warnings.append(f"{rel}: context '{ctx}' unknown, skipped")
            continue
        idx = " ".join(scalar(fm, "index", rel, warnings).replace("|", "/").split())
        if len(idx) > MAX_INDEX:
            warnings.append(f"{rel}: index is {len(idx)} characters (max {MAX_INDEX})")
        if not re.match(r"^\d{4}-\d\d-\d\d$", last):
            warnings.append(f"{rel}: last missing or not YYYY-MM-DD, skipped")
            continue
        repos = fm.get("repos") if isinstance(fm.get("repos"), list) else []
        cards.append(dict(name=name, rel=rel, ctx=ctx, status=status, last=last, index=idx, repos=repos))
    return cards, warnings


def render_worklist(cards, today, ctxs):
    out = HEADER.format(today=today)
    for ctx in ctxs:
        rows = sorted((c for c in cards if c["ctx"] == ctx), key=lambda c: (-int(c["last"].replace("-", "")), c["name"]))
        out += f"\n### {ctx}\n\n" + TABLE_HEAD
        for c in rows:
            out += f"| [[{c['name']}]] | {c['status']} | {c['last']} | {c['index']} |\n"
    return out


def render_repos(cards, warnings):
    home = os.path.expanduser("~")
    repos = {}
    for c in cards:
        for r in c["repos"]:
            key = os.path.expanduser(r).rstrip("/") if not r.startswith("~") else home + r[1:].rstrip("/")
            if key in repos and repos[key] != c["rel"]:
                warnings.append(f"repo {key} claimed by {repos[key]} and {c['rel']}, keeping the first")
                continue
            repos[key] = c["rel"]
    return json.dumps(dict(sorted(repos.items())), indent=2, ensure_ascii=False) + "\n"


def build(vault, today):
    cards, warnings = load_cards(vault)
    files = {
        os.path.join(vault, "System/rules/core/work-state.md"): render_worklist(cards, today, contexts(vault)),
        os.path.join(vault, "System/index/repos.json"): render_repos(cards, warnings),
    }
    return files, warnings, cards


def selftest():
    import tempfile
    with tempfile.TemporaryDirectory() as v:
        def w(rel, body):
            p = os.path.join(v, rel)
            os.makedirs(os.path.dirname(p), exist_ok=True)
            open(p, "w", encoding="utf-8").write(body)
        w("Contexts/Work/Projects/A/A.md", '---\ncontext: "[[Work]]"\nstatus: Active\nindex: "One line."\nlast: 2026-09-01\nrepos:\n  - ~/code/x/a\n---\n')
        w("Contexts/Work/Projects/B/B.md", '---\ncontext: "[[Work]]"\nstatus: Blocked\nindex: "Newer."\nlast: 2026-09-20\nrepos: [~/code/x/b]\n---\n')
        w("Contexts/Work/Projects/C/C.md", '---\ncontext: "[[Work]]"\nstatus: Closed\nindex: x\nlast: 2026-09-20\n---\n')
        w("Contexts/Work/Projects/A/Log.md", "---\ncontext: x\n---\n")
        w("Contexts/Work/Projects/A/Documents/Doc.md", "---\nstatus: Active\n---\n")
        w("Contexts/Personal/Projects/North/North.md", '---\ncontext: "[[Personal]]"\nstatus: Active\nindex: Star.\nlast: 2026-09-05\n---\n')
        w("Contexts/Personal/Projects/L/L.md", '---\ncontext:\n  - "[[Personal]]"\nstatus: Active\nindex: List.\nlast: 2026-09-02\n---\n')
        files, warns, cards = build(v, "2026-09-30")
        assert warns == ["Contexts/Personal/Projects/L/L.md: context is a list, using the first item"], warns
        warns.clear()
        ws = files[os.path.join(v, "System/rules/core/work-state.md")]
        assert [c["name"] for c in cards] == ["L", "North", "A", "B"], cards
        assert ws.index("### Personal") < ws.index("### Work")
        assert ws.index("[[B]]") < ws.index("[[A]]"), "newest first"
        assert "| [[North]] | Active | 2026-09-05 | Star. |" in ws
        assert "[[C]]" not in ws and not warns
        repos = json.loads(files[os.path.join(v, "System/index/repos.json")])
        assert repos[os.path.expanduser("~/code/x/b")] == "Contexts/Work/Projects/B/B.md", repos
    print("selftest ok")


def main():
    if "--selftest" in sys.argv:
        return selftest()
    check = "--check" in sys.argv
    files, warnings, cards = build(VAULT, dt.date.today().isoformat())
    changed = False
    for path, new in files.items():
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
        if old == new:
            continue
        changed = True
        rel = os.path.relpath(path, VAULT)
        if check:
            sys.stdout.writelines(difflib.unified_diff(old.splitlines(True), new.splitlines(True), rel, rel + " (generated)", n=0))
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            open(path, "w", encoding="utf-8").write(new)
            print("wrote", rel)
    for w in warnings:
        print("warning:", w, file=sys.stderr)
    print(f"{len(cards)} projects" + (", out of date" if changed and check else ", up to date" if not changed else ""))
    return 1 if (check and changed) else 0


if __name__ == "__main__":
    sys.exit(main())
