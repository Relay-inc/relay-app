// The type registry: what a note type is, in one place. Fields (key, kind, allowed values, link target), required keys,
// the home (a key of homes.rs), the template and the default collection columns. The defaults ship once, in
// resources/types.json; a vault overrides per type under `types` in `.relay/config.json`, the way `homes` does
// ({"types": {"Meeting": {"home": null}}}: a key given replaces the default's, null removes it). The set of types is
// fixed: a name the defaults do not know is ignored. Tidy, new notes, the collections, the Properties editors and the
// Claude rule (`rules/vault/types.md`, written from this) all read it, so they cannot disagree.

use serde_json::Value;
use std::path::Path;

const DEFAULTS: &str = include_str!("../resources/types.json");
/// Where the rule goes, relative to the brain folder (vault.rs: System/ or Resources/Meta/Claude/).
const RULE: &str = "rules/vault/types.md";

/// The types as resolved for a vault: the defaults with its overrides on top. An array, in the defaults' order.
pub fn load(vault: &Path) -> Vec<Value> {
    let mut types: Vec<Value> = serde_json::from_str(DEFAULTS).expect("resources/types.json");
    let cfg = crate::relay_config::load(&vault.to_string_lossy());
    for t in &mut types {
        let Some(over) = cfg.as_ref().and_then(|c| c["types"][t["name"].as_str().unwrap_or("")].as_object()) else { continue };
        for (k, v) in over { if k != "name" { if v.is_null() { t.as_object_mut().unwrap().remove(k); } else { t[k] = v.clone(); } } }
    }
    types
}

/// The home a type goes to (a key of homes.rs), None for a type without one. A type is found by its name or an alias,
/// in any case; a journal is a daily note only when it is named for a day.
pub fn home_of(types: &[Value], kind: &str, stem: &str) -> Option<String> {
    let k = kind.to_lowercase();
    let t = types.iter().find(|t| t["name"].as_str().is_some_and(|n| n.to_lowercase() == k) || t["aliases"].as_array().is_some_and(|a| a.iter().any(|x| x.as_str() == Some(&k))))?;
    if k == "journal" && !crate::tidy::dated(stem) { return None; }
    t["home"].as_str().filter(|h| !h.is_empty()).map(String::from)
}

/// The rule file's text. Prose for Claude, then a block the default vault's hook reads with sed: one line per type,
/// `Name: required keys`.
fn rule(types: &[Value]) -> String {
    let list = |v: &Value| v.as_array().map(|a| a.iter().filter_map(Value::as_str).collect::<Vec<_>>().join(", ")).unwrap_or_default();
    let mut out = String::from("<!-- Generated by Relay from the type registry (resources/types.json plus `types` in .relay/config.json). Edits here are overwritten. -->\n\n# Note types\n\nEvery note has a `type:` from this list. Make a new note from its template in `Resources/Templates/` and put it in its home.\n");
    for t in types {
        let name = t["name"].as_str().unwrap_or("");
        out += &format!("\n## {name}\n\n");
        if let Some(x) = t["template"].as_str() { out += &format!("- Template: `{x}`\n"); }
        if let Some(x) = t["home"].as_str() { out += &format!("- Home: the `{x}` folder\n"); }
        if !list(&t["required"]).is_empty() { out += &format!("- Required: {}\n", list(&t["required"])); }
        for f in t["fields"].as_array().into_iter().flatten() {
            let (key, kind) = (f["key"].as_str().unwrap_or(""), f["kind"].as_str().unwrap_or("text"));
            let more = match (f["values"].is_array(), f["target"].as_str()) { (true, _) => format!(": {}", list(&f["values"])), (_, Some(t)) => format!(" to a {t}"), _ => String::new() };
            out += &format!("- `{key}` ({kind}{more})\n");
        }
    }
    out += "\n<!-- required\n";
    for t in types { out += &format!("{}: {}\n", t["name"].as_str().unwrap_or(""), list(&t["required"])); }
    out + "-->\n"
}

/// Writes the rule into the vault's brain folder when the registry's text differs from the file; a vault without one
/// is left alone.
pub fn write_rule(vault: &Path) {
    let Some(brain) = crate::vault::BRAINS.iter().map(|b| vault.join(b)).find(|b| b.is_dir()) else { return };
    let (file, text) = (brain.join(RULE), rule(&load(vault)));
    if std::fs::read_to_string(&file).is_ok_and(|old| old == text) { return; }
    std::fs::create_dir_all(file.parent().unwrap()).ok();
    crate::util::write_file(&file, text).ok();
}

#[cfg(test)]
mod tests {
    use super::*;

    fn vault(name: &str, config: &str) -> std::path::PathBuf {
        let d = std::env::temp_dir().join(format!("relay-types-{name}-{}", std::process::id()));
        std::fs::remove_dir_all(&d).ok();
        std::fs::create_dir_all(d.join(".relay")).unwrap();
        std::fs::create_dir_all(d.join("System")).unwrap();
        std::fs::write(d.join(".relay/config.json"), config).unwrap();
        d
    }

    #[test]
    fn the_defaults_have_the_eight_types_and_their_homes() {
        let d = vault("defaults", "{}");
        let t = load(&d);
        for n in ["Context", "Project", "Meeting", "Person", "Document", "Thread", "Daily", "Transcript"] { assert!(t.iter().any(|x| x["name"] == n), "{n}"); }
        assert_eq!(home_of(&t, "Meeting", "").as_deref(), Some("meeting"));
        assert_eq!(home_of(&t, "transcript", "").as_deref(), Some("meeting"));
        assert_eq!(home_of(&t, "Daily", "").as_deref(), Some("daily"));
        assert_eq!(home_of(&t, "Journal", "2026-11-04").as_deref(), Some("daily"));
        assert_eq!(home_of(&t, "Journal", "Thoughts"), None);
        assert_eq!(home_of(&t, "Project", ""), None);
        assert_eq!(home_of(&t, "Unknown", ""), None);
    }

    #[test]
    fn a_vault_overrides_a_type_and_cannot_add_one() {
        let d = vault("override", r#"{"types":{"Meeting":{"home":null,"required":["about"]},"Podcast":{"home":"meeting"}}}"#);
        let t = load(&d);
        assert_eq!(home_of(&t, "Meeting", ""), None);
        assert_eq!(t.iter().find(|x| x["name"] == "Meeting").unwrap()["required"], serde_json::json!(["about"]));
        assert_eq!(home_of(&t, "Transcript", "").as_deref(), Some("meeting"));
        assert!(!t.iter().any(|x| x["name"] == "Podcast"));
    }

    #[test]
    fn the_rule_is_written_marked_generated_and_follows_the_registry() {
        let d = vault("rule", "{}");
        write_rule(&d);
        let file = d.join("System/rules/vault/types.md");
        let text = std::fs::read_to_string(&file).unwrap();
        assert!(text.starts_with("<!-- Generated by Relay"));
        assert!(text.contains("- Home: the `meeting` folder"));
        assert!(text.contains("- `status` (select: Active, Blocked, Quiet, Paused, Closed)"));
        assert!(text.contains("\nMeeting: context\n") && text.contains("\nPerson: \n"));
        std::fs::write(d.join(".relay/config.json"), r#"{"types":{"Meeting":{"required":["context","about"]}}}"#).unwrap();
        write_rule(&d);
        assert!(std::fs::read_to_string(&file).unwrap().contains("\nMeeting: context, about\n"));
    }

    #[test]
    fn a_vault_without_a_brain_folder_gets_no_rule() {
        let d = vault("nobrain", "{}");
        std::fs::remove_dir_all(d.join("System")).unwrap();
        write_rule(&d);
        assert!(!d.join("System").exists());
    }

    /// The default vault's hook run on a note: the reason it blocks with, "" when it lets the note through.
    fn hook(d: &std::path::Path, note: &str) -> Option<String> {
        use std::io::Write;
        let file = d.join("Contexts/Work/Note.md");
        std::fs::create_dir_all(file.parent().unwrap()).unwrap();
        std::fs::write(&file, note).unwrap();
        let script = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("resources/default-vault/System/hooks/validate-frontmatter.sh");
        std::fs::create_dir_all(d.join("System/hooks")).unwrap();
        std::fs::copy(script, d.join("System/hooks/validate-frontmatter.sh")).unwrap();
        let mut child = std::process::Command::new("bash").arg(d.join("System/hooks/validate-frontmatter.sh"))
            .stdin(std::process::Stdio::piped()).stdout(std::process::Stdio::piped()).spawn().ok()?;
        child.stdin.take().unwrap().write_all(format!(r#"{{"tool_input":{{"file_path":"{}"}}}}"#, file.display()).as_bytes()).unwrap();
        Some(String::from_utf8_lossy(&child.wait_with_output().ok()?.stdout).into_owned())
    }

    #[test]
    fn the_default_vault_hook_blocks_a_note_without_a_required_key_of_its_type() {
        if std::process::Command::new("jq").arg("--version").output().is_err() { return; }
        let d = vault("hook", "{}");
        write_rule(&d);
        assert_eq!(hook(&d, "---\ntype: Meeting\ncontext: \"[[Work]]\"\n---\n").unwrap(), "");
        assert!(hook(&d, "---\ntype: Meeting\ndate: 2026-11-05\n---\n").unwrap().contains("needs `context:`"));
        assert!(hook(&d, "---\ntype: Meeting\ncontext: Work\n---\n").unwrap().contains("must be a wikilink"));
        assert!(hook(&d, "---\ntype: Podcast\n---\n").unwrap().contains("Invalid type"));
        assert_eq!(hook(&d, "---\ntype: Person\n---\n").unwrap(), "");
        // the registry decides: Person made to require `company`
        std::fs::write(d.join(".relay/config.json"), r#"{"types":{"Person":{"required":["company"]}}}"#).unwrap();
        write_rule(&d);
        assert!(hook(&d, "---\ntype: Person\n---\n").unwrap().contains("needs `company:`"));
    }
}
