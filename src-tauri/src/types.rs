// The type registry: what each note type is (its fields, the keys it needs, its home, its template, its collection's
// columns and sort), in one file every part of Relay reads: `.relay/types.json` in the vault, the shipped defaults
// (resources/default-vault/.relay/types.json) when the vault has none. JSON, so nothing needs a YAML parser to read it,
// and the vault hook reads it with jq. A fixed set of types: variation goes in a subtype field (`document-type:`).
//
// From the registry Relay writes the vault's Claude rule `<rules>/vault/types.md` (RULE), so every Claude session sees
// the same schema. That file says it is generated and is only ever written over when it still says so.

use serde::{Deserialize, Serialize};
use std::fs;
use std::path::{Path, PathBuf};

const SHIPPED: &str = include_str!("../resources/default-vault/.relay/types.json");
/// The first line of the generated rule: Relay writes over a file that starts with it, never over another.
const MARK: &str = "<!-- Generated by Relay from .relay/types.json: edit that file, not this one. -->";

/// One frontmatter key of a type. `kind`: text, date, select (one of `values`), link (to a note of a `target` type),
/// people (a list of links to `target` notes), check.
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
pub struct Field {
    pub key: String,
    pub kind: String,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub values: Vec<String>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub target: Vec<String>,
}
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
pub struct Sort { pub key: String, pub dir: String }
/// A note type. `home` is a key of homes.rs (the folder can be set per vault under `homes` in .relay/config.json);
/// `template` a path relative to the vault; `columns` and `sort` the collection's defaults (keys; derived ones such as
/// `title`, `stage`, `updated` included).
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
pub struct Type {
    pub name: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub home: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub template: Option<String>,
    #[serde(default)]
    pub required: Vec<String>,
    #[serde(default)]
    pub fields: Vec<Field>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub columns: Vec<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub sort: Option<Sort>,
}
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
pub struct Registry { pub types: Vec<Type> }

pub fn path(vault: &Path) -> PathBuf { vault.join(".relay/types.json") }

/// The vault's registry; the shipped one when it has none or it does not parse.
pub fn load(vault: &Path) -> Registry {
    let own = fs::read_to_string(path(vault)).ok().and_then(|t| serde_json::from_str(&t).map_err(|e| eprintln!("types.json: {e}")).ok());
    own.unwrap_or_else(|| serde_json::from_str(SHIPPED).expect("the shipped types.json parses"))
}

impl Registry {
    /// A type by its name as a note writes it in `type:` (any case).
    pub fn get(&self, name: &str) -> Option<&Type> { self.types.iter().find(|t| t.name.eq_ignore_ascii_case(name.trim())) }
    /// The home a note of `kind` named `stem` goes to, None for a type without one. The daily home only takes notes named
    /// for a day (a journal entry called something else stays where it is).
    pub fn home_of(&self, kind: &str, stem: &str) -> Option<&str> {
        self.get(kind)?.home.as_deref().filter(|h| *h != "daily" || crate::tidy::dated(stem))
    }
    /// Every home the types use, once each, in the registry's order.
    pub fn homes(&self) -> Vec<&str> {
        let mut out: Vec<&str> = vec![];
        for h in self.types.iter().filter_map(|t| t.home.as_deref()) { if !out.contains(&h) { out.push(h); } }
        out
    }
}

/// The Claude rule for a registry, with each home's folder as this vault has it.
pub fn rule(reg: &Registry, vault: &Path) -> String {
    let code = |s: &str| format!("`{s}`");
    let names = |l: &[String]| l.join(" or ");
    let mut out = format!("{MARK}\n\n# Note types\n\nEvery note has `type:` set to one of the types below; there are no others. Variation within a type goes in a subtype field (`document-type:`), not in a new type. A new note starts from its type's template, goes in its type's home when it has one, and has every required key filled. Links are written as `\"[[Note name]]\"`.\n");
    for t in &reg.types {
        out += &format!("\n## {}\n\n", t.name);
        if let Some(h) = &t.home {
            let dir = crate::homes::home(vault, h, "{yyyy}");
            out += &format!("- Home: {}, `{{yyyy}}` the note's year\n", code(&format!("{}/", dir.strip_prefix(vault).unwrap_or(&dir).display())));
        }
        if let Some(p) = &t.template { out += &format!("- Template: {}\n", code(p)); }
        if !t.required.is_empty() { out += &format!("- Required: {}\n", t.required.iter().map(|k| code(k)).collect::<Vec<_>>().join(", ")); }
        for f in &t.fields {
            let what = match f.kind.as_str() {
                "date" => "a date, YYYY-MM-DD".to_string(),
                "select" => format!("one of {}", f.values.join(", ")),
                "link" if f.target.is_empty() => "a link to a note".to_string(),
                "link" => format!("a link to a {} note", names(&f.target)),
                "people" => format!("a list of links to {} notes", names(&f.target)),
                "check" => "true or false".to_string(),
                _ => "text".to_string(),
            };
            out += &format!("- {}: {what}\n", code(&f.key));
        }
    }
    out
}

/// Where the vault's generated rule goes: under its Claude rules folder (`System/rules`, else `.claude/rules`), None for
/// a vault without one or whose rules folder leads out of it.
fn rule_path(vault: &Path) -> Option<PathBuf> {
    let root = fs::canonicalize(vault).ok()?;
    let rules = ["System/rules", ".claude/rules"].iter().map(|d| vault.join(d)).find(|d| d.is_dir())?;
    fs::canonicalize(&rules).ok()?.starts_with(&root).then(|| rules.join("vault/types.md"))
}

/// Write the vault's generated rule when it differs from the registry's. A file of that name somebody wrote themselves
/// (without MARK) stays as it is.
pub fn write_rule(vault: &Path) {
    let Some(p) = rule_path(vault) else { return };
    let text = rule(&load(vault), vault);
    match fs::read_to_string(&p) {
        Ok(old) if old == text || !old.starts_with(MARK) => return,
        _ => {}
    }
    if let Some(d) = p.parent() { fs::create_dir_all(d).ok(); }
    if let Err(e) = crate::util::write_file(&p, text) { eprintln!("types rule: {e}"); }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tmp(name: &str) -> PathBuf {
        let d = std::env::temp_dir().join(format!("relay-types-{name}-{}", std::process::id()));
        fs::remove_dir_all(&d).ok();
        fs::create_dir_all(&d).unwrap();
        fs::canonicalize(d).unwrap()
    }
    fn w(root: &Path, rel: &str, body: &str) { let p = root.join(rel); fs::create_dir_all(p.parent().unwrap()).unwrap(); fs::write(p, body).unwrap(); }
    fn shipped() -> PathBuf { Path::new(env!("CARGO_MANIFEST_DIR")).join("resources/default-vault") }

    #[test]
    fn a_vault_without_a_registry_gets_the_shipped_one_and_its_own_wins() {
        let v = tmp("load");
        let reg = load(&v);
        for t in ["Context", "Project", "Meeting", "Person", "Document", "Thread", "Daily", "Transcript"] { assert!(reg.get(t).is_some(), "{t}"); }
        assert_eq!(reg.get("meeting").unwrap().required, ["context"]);
        assert_eq!(reg.homes(), ["meeting", "thread", "daily"]);
        w(&v, ".relay/types.json", r#"{"types":[{"name":"Meeting","fields":[{"key":"room","kind":"text"}]}]}"#);
        let own = load(&v);
        assert_eq!(own.types.len(), 1);
        assert_eq!(own.get("Meeting").unwrap().fields[0].key, "room");
        // a file that does not parse is no registry
        w(&v, ".relay/types.json", "{ not json");
        assert_eq!(load(&v), reg);
    }

    #[test]
    fn home_of_reads_the_registry() {
        let reg = load(&tmp("homes"));
        assert_eq!(reg.home_of("Meeting", "x"), Some("meeting"));
        assert_eq!(reg.home_of("TRANSCRIPT", "x"), Some("meeting"));
        assert_eq!(reg.home_of("thread", ""), Some("thread"));
        assert_eq!(reg.home_of("Daily", "2026-11-04"), Some("daily"));
        assert_eq!(reg.home_of("journal", "2026-11-04 Morning"), Some("daily"));
        assert_eq!(reg.home_of("journal", "Morning"), None);
        assert_eq!(reg.home_of("Document", "x"), None);
        assert_eq!(reg.home_of("Nothing", "x"), None);
    }

    #[test]
    fn the_rule_is_generated_written_on_change_and_never_over_a_hand_written_one() {
        // snapshot: the rule the starter vault ships is the one its registry makes
        let v = tmp("rule");
        assert_eq!(rule(&load(&v), &v), fs::read_to_string(shipped().join("System/rules/vault/types.md")).unwrap());
        // no rules folder: nothing written
        write_rule(&v);
        assert!(!v.join("System").exists());
        fs::create_dir_all(v.join("System/rules")).unwrap();
        write_rule(&v);
        let p = v.join("System/rules/vault/types.md");
        let text = fs::read_to_string(&p).unwrap();
        assert!(text.starts_with(MARK) && text.contains("## Meeting") && text.contains("- Home: `Calendar/Meetings/{yyyy}/`"), "{text}");
        // the registry and the vault's homes change: the rule follows
        w(&v, ".relay/types.json", r#"{"types":[{"name":"Meeting","home":"meeting","required":["about"]}]}"#);
        w(&v, ".relay/config.json", r#"{"homes":{"meeting":"Meetings/{yyyy}"}}"#);
        write_rule(&v);
        let text = fs::read_to_string(&p).unwrap();
        assert!(text.contains("- Home: `Meetings/{yyyy}/`") && text.contains("- Required: `about`") && !text.contains("## Person"), "{text}");
        // a hand-written file of that name stays
        fs::write(&p, "my own types\n").unwrap();
        write_rule(&v);
        assert_eq!(fs::read_to_string(&p).unwrap(), "my own types\n");
    }

    /// Runs the starter vault's frontmatter hook on `note` (written at `rel` in a vault with the shipped registry).
    fn hook(v: &Path, rel: &str, note: &str) -> String {
        use std::io::Write;
        w(v, rel, note);
        let mut c = std::process::Command::new("bash").arg(shipped().join("System/hooks/validate-frontmatter.sh"))
            .env("CLAUDE_PROJECT_DIR", v).stdin(std::process::Stdio::piped()).stdout(std::process::Stdio::piped()).spawn().unwrap();
        let input = serde_json::json!({"tool_input": {"file_path": v.join(rel)}}).to_string();
        c.stdin.take().unwrap().write_all(input.as_bytes()).unwrap();
        String::from_utf8(c.wait_with_output().unwrap().stdout).unwrap()
    }

    #[test]
    fn the_starter_hook_checks_notes_against_the_registry() {
        // the hook needs jq, as the starter's other hooks do
        if !std::process::Command::new("bash").args(["-c", "command -v jq"]).output().is_ok_and(|o| o.status.success()) { return eprintln!("no jq: hook not run"); }
        let v = tmp("hook");
        w(&v, ".relay/types.json", SHIPPED);
        let blocked = |out: &str| out.contains("\"block\"");
        assert!(!blocked(&hook(&v, "a.md", "---\ntype: Meeting\ncontext: \"[[Work]]\"\n---\n")));
        let out = hook(&v, "a.md", "---\ntype: Meeting\nwith: x\n---\n");
        assert!(blocked(&out) && out.contains("context"), "{out}");
        assert!(blocked(&hook(&v, "a.md", "---\ntype: Meeting\ncontext: Work\n---\n")), "a link field takes a [[link]]");
        assert!(!blocked(&hook(&v, "a.md", "---\ntype: Meeting\ncontext:\n  - \"[[Work]]\"\n---\n")), "a list holds the link");
        assert!(blocked(&hook(&v, "a.md", "---\ntype: Recipe\n---\n")), "a type the registry does not have");
        assert!(blocked(&hook(&v, "a.md", "---\ntitle: x\n---\n")), "no type");
        assert!(!blocked(&hook(&v, "a.md", "---\ntype: Daily\n---\n")), "a type without required keys");
        // the registry decides: Meeting needs nothing once the vault says so
        w(&v, ".relay/types.json", r#"{"types":[{"name":"Meeting"}]}"#);
        assert!(!blocked(&hook(&v, "a.md", "---\ntype: Meeting\n---\n")));
    }
}
